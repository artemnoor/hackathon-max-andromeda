import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

function argumentValue(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return undefined;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} requires a value`);
  return value;
}

const expected = resolve(
  process.env.API_TYPES_OUTPUT ?? argumentValue("--output") ?? "src/lib/generated.ts",
);
const tempSpec = resolve(".tmp-openapi.json");
const sourceFile = process.env.OPENAPI_FILE ?? argumentValue("--spec") ?? tempSpec;
if (!process.env.OPENAPI_FILE) {
  if (sourceFile === tempSpec) {
    const response = await fetch(process.env.OPENAPI_URL ?? "http://127.0.0.1:8000/openapi.json");
    if (!response.ok) throw new Error(`OpenAPI request failed with ${response.status}`);
    await writeFile(tempSpec, JSON.stringify(await response.json()), "utf8");
  }
}

try {
  const before = (await readFile(expected, "utf8")).replace(/\r\n/g, "\n");
  const schema = JSON.parse(await readFile(sourceFile, "utf8"));
  const ast = await openapiTS(schema);
  const after = `/* Generated by scripts/generate-api.mjs. Do not edit. */\n\n${astToString(ast)}`;
  if (before !== after) {
    throw new Error(`Generated client is stale at ${expected}. Regenerate it and review the contract change.`);
  }
  console.log(`Generated client ${expected} matches ${sourceFile}.`);
} finally {
  if (!process.env.OPENAPI_FILE && sourceFile === tempSpec) {
    await import("node:fs/promises").then(({ unlink }) => unlink(tempSpec).catch(() => undefined));
  }
}
